def _classify_field(text, current, state, profile):
    """用大模型判断用户这次输入的信息实际属于哪一类(学校/城市/专业/学历/本科类型/学制)。"""
    t = (text or "").strip()
    cleaned = t.strip("。！!？?,. ")
    # 确认词且当前项已有档案值 → 视为确认当前项,避免额外一次模型调用
    if cleaned in CONFIRM_WORDS and (profile.get(_PROFILE_KEY[current]) or "").strip():
        return current
    # 数字+“年”或明确“学制”→ 学制(精确规则,不必再请求模型)
    if re.search(r"(\d+|[一二三四五六七八九十]+)\s*年|学制\s*\d|学几年", t):
        return "study_years"
    # 精确规则(不依赖模型):明确“职业本科/普通本科”一定是本科类型;单独“本科/专科/大专/高职/硕士/博士/学士”=学历
    if "职业本科" in t or "普通本科" in t:
        return "degree_type"
    if re.fullmatch(r"(本科|专科|大专|高职|研究生|硕士|博士|学士)", cleaned):
        return "degree"
    system = (
        "你是信息分类器。用户在填写【学校/学历/专业/本科类型(职业本科或普通本科)/学制/城市】这几类信息。"
        "请根据用户这次输入内容的语义,判断它实际上属于哪一类,不要被当前正在问哪一项影响。"
        '只输出一个 JSON:{"field":"school|city|major|degree|degree_type|study_years|unknown"}。'
        "判定:含“大学/学院/学校/职业技术学院”等高校词→school;城市或行政区(如武汉、北京、xx市)→city;"
        "含“专业/工程/机械/自动化/电气/电子/计算机/机器人/车辆”等→major;"
        "单独的“本科/专科/研究生/硕士/博士/学士”(未带“职业/普通”)→degree(学历);"
        "只有明确“职业本科”或“普通本科”这类完整类型词→degree_type(本科类型),不要因为“本科”二字含在“职业本科”里就把“本科”判成 degree_type;"
        "含“年/学制/学几年”(如4年/3年)→study_years。"
        "若用户只回答确认词(确认/对/是)且该项为当前项,返回当前项;实在无法判断→unknown。"
    )
    user = (
        f"当前正在问:{_field_cn(current)}\n已确认信息:{_fmt_known(state, profile)}\n"
        f"用户输入:{t}"
    )
    try:
        data = llm.chat_json(
            [{"role": "system", "content": system}, {"role": "user", "content": user}],
            temperature=0,
            max_tokens=384000,
        )
        f = (data.get("field") or "unknown").strip().lower()
    except Exception:
        f = "unknown"
    return f if f in _BASIC_FIELDS else "unknown"


def _apply_field(state, field, text, profile, pending):
    """把某一类型的用户输入写入 state;对 degree 会按是否本科判断是否还需要 degree_type。"""
    if field == "school":
        state["school"] = _confirm_value(text, profile.get("user_school"))
    elif field == "city":
        state["city"] = _confirm_value(text, profile.get("user_city"))
    elif field == "major":
        state["major"] = _confirm_value(text, profile.get("user_major"))
    elif field == "degree":
        val = _confirm_value(text, profile.get("user_degree"))
        state["degree"] = val
        v = (val or "").strip()
        if "职业本科" in v:
            state["degree_type"] = "职业本科"
            if "degree_type" in pending:
                pending.remove("degree_type")
        elif "普通本科" in v:
            state["degree_type"] = "普通本科"
            if "degree_type" in pending:
                pending.remove("degree_type")
        elif "本科" in v:
            # 若本科类型尚未确定,用档案兜底;若已确定则不再重复询问
            if not (state.get("degree_type") or "").strip():
                state["degree_type"] = profile.get("user_degree_type") or ""
            if (state.get("degree_type") or "").strip():
                if "degree_type" in pending:
                    pending.remove("degree_type")
            else:
                # 学历为本科但本科类型未知 → 标记需要再问本科类型(在 _advance_basic 里插到队首)
                state["_need_degree_type"] = True
        else:
            state["degree_type"] = ""
            if "degree_type" in pending:
                pending.remove("degree_type")
    elif field == "degree_type":
        raw = (text or "").strip()
        if "职业本科" in raw:
            state["degree_type"] = "职业本科"
        elif "普通本科" in raw:
            state["degree_type"] = "普通本科"
        else:
            state["degree_type"] = _confirm_value(raw, profile.get("user_degree_type"))
        # 已知本科类型说明是本科,若学历未填则顺带补上
        if not (state.get("degree") or "").strip() and state.get("degree_type"):
            state["degree"] = "本科" if "本科" in state["degree_type"] else state["degree_type"]
    elif field == "study_years":
        state["study_years"] = _confirm_value(text, profile.get("user_study_years"))


