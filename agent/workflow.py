SEMESTER_RE = re.compile(
    r"(大一上|大一下|大二上|大二下|大三上|大三下|大四上|大四下|第[一二三四五六七八]学期)"
)


def _fallback_graph(plan_text):
    """LLM 提炼失败时,从计划文本提取学期与要点,构建最简 nodes/edges 图谱。

    保证“一键导入”始终可用:即使大模型偶发返回空,也能产出合法 JSON。
    """
    text = plan_text or ""
    nodes = []
    edges = []
    node_type = {}

    def add_node(label, ntype="要点"):
        if label in node_type:
            return label
        node_type[label] = ntype
        nodes.append({"label": label, "type": ntype, "properties": {}})
        return label

    def clean_line(raw):
        line = raw.strip().lstrip("-#*|>·").strip()
        line = re.sub(r"^[\d]+[.、)]\s*", "", line).strip()
        line = re.sub(r"[*`【】\[\]]", "", line).strip()
        # 去掉行尾视频链接,只留描述
        line = re.split(r"https?://|\[|\(", line)[0].strip()
        return line

    marks = list(SEMESTER_RE.finditer(text))
    if marks:
        for idx, m in enumerate(marks):
            sem = m.group(1)
            add_node(sem, "学期")
            start = m.end()
            end = marks[idx + 1].start() if idx + 1 < len(marks) else len(text)
            block = text[start:end]
            count = 0
            for raw in block.splitlines():
                line = clean_line(raw)
                if not line or len(line) < 2 or len(line) > 20 or line == sem:
                    continue
                key = line
                if key not in node_type:
                    # 简单类型推断
                    if "证" in key:
                        ntype = "证书"
                    elif any(k in key for k in ("Python", "MATLAB", "SolidWorks", "软件", "工具")):
                        ntype = "工具"
                    elif "岗位" in key or "工程师" in key:
                        ntype = "岗位"
                    else:
                        ntype = "课程"
                    add_node(key, ntype)
                edges.append({"source": sem, "target": line, "label": "包含"})
                count += 1
                if count >= 8:
                    break
    else:
        root = add_node("四年学习计划", "目标")
        for raw in text.splitlines():
            line = clean_line(raw)
            if not line or len(line) < 2 or len(line) > 20:
                continue
            item = add_node(line, "要点")
            edges.append({"source": root, "target": item, "label": "包含"})
            if len(nodes) > 24:
                break

    # 去重边,避免重复
    seen = set()
    dedup_edges = []
    for e in edges:
        key = (e["source"], e["target"], e["label"])
        if key in seen:
            continue
        seen.add(key)
        dedup_edges.append(e)
    if not nodes:
        nodes.append({"label": "四年学习计划", "type": "目标", "properties": {}})
    return {"nodes": nodes, "edges": dedup_edges}


def _full_conversation_text(messages):
    """把完整聊天记录渲染成不压缩的文本,供知识图谱模型理解整段上下文。"""
    if not messages:
        return ""
    parts = []
    for m in messages:
        role = m.get("role") or ""
        who = "用户" if role == "user" else "助手"
        parts.append(f"[{who}]\n{m.get('content') or ''}")
    return "\n\n".join(parts)


def _knowledge_graph(conversation):
    """把完整对话(不压缩)提炼为 nodes/edges 的知识图谱 JSON 字符串。

    失败时重试一次,仍失败则用兜底图谱兜底,保证返回的始终是合法 nodes/edges 结构。
    """
    last_err = None
    for _ in range(2):
        try:
            data = llm.chat_json(
                [
                    {"role": "system", "content": SYSTEM_GRAPH},
                    {"role": "user", "content": (
                        "请仔细阅读下面的完整聊天记录(含用户基本信息、意向公司/岗位、四年学习计划、证书、竞赛等关键信息),"
                        "按系统提示词与《计算机发展.json》格式,仅输出一个含 nodes 和 edges 两个数组的 JSON 对象,"
                        "不要输出任何其他文字,不要 Markdown 代码块:\n\n" + conversation
                    )},
                ],
                temperature=0.2,
                max_tokens=384000,
                model=llm.MODEL_PRO,
            )
            nodes = data.get("nodes") if isinstance(data, dict) else None
            edges = data.get("edges") if isinstance(data, dict) else None
            if isinstance(nodes, list) and isinstance(edges, list):
                return json.dumps(data, ensure_ascii=False, indent=2)
            last_err = ValueError("返回结构缺少 nodes/edges")
        except Exception as exc:
            last_err = exc
    print(f"[workflow] 知识图谱生成失败({last_err}),使用兜底图谱")
    return json.dumps(_fallback_graph(conversation), ensure_ascii=False, indent=2)


