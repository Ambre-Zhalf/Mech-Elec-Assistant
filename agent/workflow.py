def _confirm_value(text, existing):
    """用户回复为确认词时沿用档案值,否则采用新输入。"""
    cleaned = text.strip().strip("。！!？?,. ")
    if existing and cleaned in CONFIRM_WORDS:
        return existing
    return cleaned or existing


def _emit_body(emit, text, stream):
    """把正文输出到前端;流式模式下按小块输出以呈现打字机效果。"""
    if not text:
        return
    if not stream:
        emit("content", {"delta": text})
        return
    chunk = 24
    for i in range(0, len(text), chunk):
        emit("content", {"delta": text[i : i + chunk]})
        time.sleep(0.012)


def _emit_process(emit, text):
    emit("process", {"text": text})


# ---------- 思考过程/用时缓存:供写消息时一并落库 ----------
_THINK_BUFFER = {}


def _think_start(session_id):
    _THINK_BUFFER[session_id] = {"lines": [], "start": time.time()}


def _think_push(session_id, text):
    b = _THINK_BUFFER.setdefault(session_id, {"lines": [], "start": time.time()})
    if text:
        b["lines"].append(text)


def _think_take(session_id):
    b = _THINK_BUFFER.pop(session_id, None)
    if not b:
        return [], None
    secs = (time.time() - b["start"]) if b.get("start") else None
    return b.get("lines") or [], secs


def _deliver(emit, session_id, text, stream):
    """输出助手正文,并写入当前会话的历史消息。"""
    if text:
        mode = (store.get_session(session_id) or {}).get("mode") or "plan"
        think_lines, think_time = _think_take(session_id)
        store.add_message(
            session_id,
            "assistant",
            text,
            mode=mode,
            think="\n".join(think_lines) if think_lines else "",
            think_time=think_time,
        )
    _emit_body(emit, text, stream)


