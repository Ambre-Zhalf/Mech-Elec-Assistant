def _handle_basic_field(session_id, state, text, profile, emit, stream):
    """基本信息采集节点:由大模型识别用户输入的类型;若填错类型,则“将错就错”提前处理,
    把当前应问的类型顺延到后面,其余类型保持原有顺序。"""
    current = state.get("step") or _BASIC_FIELDS[0]
    pending = state.get("pending") or list(_BASIC_FIELDS)
    memories = store.search_memory(session_id, text)
    field = _classify_field(text, current, state, profile)

    # 防御:问“本科类型”时,若模型把“普通本科/职业本科”误判成学历,重新归为本科类型
    if current == "degree_type" and field == "degree" and ("职业本科" in (text or "") or "普通本科" in (text or "")):
        field = "degree_type"

    # 学历/本科类型互推:问“学历”时用户答了“职业本科/普通本科”(分类有时判成 degree_type),
    # 视为“学历+类型”都已填好,直接进入下一项,避免后面重复问“学历”导致死循环。
    if current == "degree" and field == "degree_type":
        raw = (text or "").strip()
        if "职业本科" in raw or "普通本科" in raw:
            state["degree_type"] = "职业本科" if "职业本科" in raw else "普通本科"
            if not (state.get("degree") or "").strip():
                state["degree"] = "本科"
            for f in ("degree", "degree_type"):
                if f in pending:
                    pending.remove(f)
        else:
            # 只答了“本科/专科”等,未给出类型:视为填了学历,类型仍待询问
            state["degree"] = _confirm_value(raw, profile.get("user_degree"))
            if "degree" in pending:
                pending.remove("degree")
        _advance_basic(session_id, state, pending, memories, profile, emit, stream)
        return

    if field == current:
        _apply_field(state, field, text, profile, pending)
        pending.pop(0)
    elif field in pending and field != current:
        # 用户填了另一类信息(填错类型)→ 将错就错,提前处理该类型,当前类型顺延
        _apply_field(state, field, text, profile, pending)
        pending.remove(field)
    else:
        # 未识别/已填过 → 温和重复当前问题
        _emit_process(emit, f"我先确认一下{_field_cn(current)}信息")
        _deliver(emit, session_id, _question_text(current, state, profile), stream)
        return
    _advance_basic(session_id, state, pending, memories, profile, emit, stream)


def _advance_basic(session_id, state, pending, memories, profile, emit, stream):
    """更新 pending/step,若基本信息填完则进入公司推荐,否则问下一项。"""
    # 学历=本科但未定本科类型时,把 degree_type 插到待问队首,先问“职业本科/普通本科”
    if state.pop("_need_degree_type", None):
        if "degree_type" not in pending:
            pending.insert(0, "degree_type")
    state["pending"] = pending
    state["step"] = pending[0] if pending else ""
    store.set_session(session_id, state)
    if not pending:
        # 基本信息填完 → 进入公司推荐
        _emit_process(emit, "正在检索与你匹配的目标企业(联网搜索)")
        state["company_output"] = _list_companies(
            state.get("major"), state.get("city"), state.get("school"), _fmt_degree(state), memories, emit
        )
        state["_last_gen"] = "companies"
        state["step"] = "company"
        store.set_session(session_id, state)
        _deliver(emit, session_id, _company_question(state["company_output"], profile), stream)
        return
    next_field = pending[0]
    _emit_process(emit, f"正在确认你的{_field_cn(next_field)}")
    _deliver(emit, session_id, _question_text(next_field, state, profile), stream)


