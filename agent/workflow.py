def classify_intent(text):
    """判断进入"规划"分支还是"导师追问"分支。"""
    if any(k in text.lower() for k in PLAN_KEYWORDS):
        return "plan"
    if any(k in text for k in FOLLOWUP_MARKERS):
        return "chat"
    system = (
        "你是意图分类器。判断用户输入是否与机电职业规划/学习计划生成相关"
        "(即用户准备提供专业、城市、学校、学历、意向公司、意向岗位等基础信息来开启新一轮规划)。"
        "如果用户只是在追问、咨询或修改已生成的计划(如问课程难度、名词解释、某软件怎么学、计划调整建议),一律返回 chat。"
        '只输出 JSON:{"intent":"plan"} 或 {"intent":"chat"}。'
    )
    try:
        data = llm.chat_json(
            [{"role": "system", "content": system}, {"role": "user", "content": text}],
            temperature=0,
        )
        return data.get("intent", "chat")
    except Exception:
        return "chat"


